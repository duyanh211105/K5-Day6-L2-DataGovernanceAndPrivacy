"""Label-free T10 summary for the report (numbers come from out/, never typed by hand).

    python -m tools.t10_summary --poc out/poc --baseline out/baseline --out reports/t10_label_free_summary.md

GT (perf_drop) is instructor-only, so this compares *rankings and flags*, not accuracy.
Official numbers: make eval-baseline eval-poc compare TRACK=t10 (needs the instructor overlay).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd
from scipy.stats import spearmanr


def _md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(str(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--poc", default="out/poc")
    ap.add_argument("--baseline", default="out/baseline")
    ap.add_argument("--out", default="reports/t10_label_free_summary.md")
    a = ap.parse_args(argv)
    poc, base = Path(a.poc), Path(a.baseline)
    p = pd.read_csv(poc / "shift_scores.csv")
    b = pd.read_csv(base / "shift_scores.csv")
    m = b[["batch_id", "shift_score", "pred_high_risk"]].rename(columns={"shift_score": "baseline_score", "pred_high_risk": "baseline_flag"}) \
        .merge(p[["batch_id", "shift_score", "pred_high_risk", "status", "s_img", "s_pred", "img_z", "pred_z", "pred_p",
                  "mean_uncertainty", "pos_rate", "top_descriptors"]], on="batch_id")
    m["baseline_rank"] = m.baseline_score.rank(ascending=False, method="min").astype(int)
    m["poc_rank"] = m.shift_score.rank(ascending=False, method="min").astype(int)
    rho = spearmanr(m.baseline_score, m.shift_score).statistic
    ri_p, ri_b = json.loads((poc / "run_info.json").read_text()), json.loads((base / "run_info.json").read_text())
    dec = json.loads((poc / "decision.json").read_text(encoding="utf-8"))
    sl = pd.read_csv(poc / "slice_scan.csv")
    q = pd.read_csv(poc / "review_queue.csv")
    body = f"""# T10 · label-free summary (generated by `python -m tools.t10_summary`)

Runs: PoC `{ri_p['git_sha']}` ({ri_p['runtime_seconds']} s, {ri_p['stats'].get('n_images')} images) ·
baseline `{ri_b['git_sha']}` ({ri_b['runtime_seconds']} s). Seed {ri_p['seed']}, offline={ri_p['offline']}.

## Per-batch scores (no GT: these are NOT accuracy numbers)

{_md(m[["batch_id", "baseline_score", "baseline_rank", "baseline_flag", "shift_score", "poc_rank", "pred_high_risk", "status"]])}

Spearman agreement between baseline and PoC rankings: **{rho:.3f}** (N=6 batches).

## PoC components

{_md(m[["batch_id", "s_img", "img_z", "s_pred", "pred_z", "pred_p", "mean_uncertainty", "pos_rate", "top_descriptors"]])}

Model-drift permutation p-values (one-sided): min = {m.loc[m.batch_id != 'b0_source', 'pred_p'].min():.3f}.
Batches with model-drift z ≥ 1.645: {int(m.pred_high_risk.sum())}.

## Slice scan

{len(sl)} batch×slice cells, {int(sl.silent_risk.sum())} flagged silent_risk. Largest uncertainty gaps:

{_md(sl.sort_values('uncertainty_gap_vs_ref', ascending=False).head(5))}

## Review + decision

Queue: {len(q)} rows ({int(q.item_id.str.startswith('batch:').sum())} batches + {int(q.item_id.str.startswith('img:').sum())} images).
Release decision: **{dec['status']}** · `{dec['reason_code']}` · owner {dec['owner']}.
> {dec['reason']}
"""
    Path(a.out).write_text(body, encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
